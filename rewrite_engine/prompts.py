def detect_language(text: str, title: str = "") -> str:
    """
    Empirically evaluated language detector for Ukrainian vs Russian reviews.
    Returns 'uk' or 'ru'.
    """
    combined = f"{title} {text}".lower()

    # Ukrainian distinct characters: і, ї, є, ґ
    ua_distinct = sum(combined.count(ch) for ch in "іїєґ’\x27") * 3
    # Russian distinct characters: ы, э, ъ, ё
    ru_distinct = sum(combined.count(ch) for ch in "ыэъё") * 3

    # Common stopwords comparison
    ua_stopwords = len(re.findall(r"\b(і|та|що|як|це|дуже|не|на|до|для|від|все|мені|було|дякую|працює|замовлення|гроші)\b", combined))
    ru_stopwords = len(re.findall(r"\b(и|что|как|это|очень|не|на|до|для|от|все|мне|было|спасибо|работает|заказ|деньги)\b", combined))

    ua_score = ua_distinct + ua_stopwords
    ru_score = ru_distinct + ru_stopwords

    if ua_score == ru_score:
        # Default to Ukrainian for equal or zero score in .ua domain
        return "uk"
    return "uk" if ua_score > ru_score else "ru"


def get_system_prompt(lang: str) -> str:
    """Returns system prompt for target language."""
    return SYSTEM_PROMPT_UK if lang == "uk" else SYSTEM_PROMPT_RU


def format_user_prompt(review: Dict[str, Any], feedback: Optional[List[str]] = None) -> str:
    """
    Formats the user message containing review content and role metadata,
    optionally appending linter corrective feedback for retries.
    """
    role = review.get("review_type", "klientov")
    role_description = "клієнт/покупець" if role == "klientov" else "співробітник/колишній працівник"
    rating = review.get("rating", "3.0")
    author = review.get("author") or "Анонім"
    title = (review.get("title") or "").strip()
    text = (review.get("text") or "").strip()

    prompt_parts = [
        "Оригінальний відгук для переписування:",
        f"- Тип відгуку: {role} ({role_description})",
        f"- Оцінка: {rating} з 5.0",
        f"- Автор: {author}",
        f"- Заголовок: {title or 'без заголовка'}",
        "- Текст:",
        '"""',
        text,
        '"""'
    ]

    if feedback:
        prompt_parts.extend([
            "",
            "УВАГА! Попередня спроба була відхилена валідатором через такі помилки:",
            *[f"- {err}" for err in feedback],
            "Виправ ці помилки! КАТЕГОРИЧНО НЕ використовуй довгі тире (—) та штампи, дотримуйся правил."
        ])

    return "\n".join(prompt_parts)
