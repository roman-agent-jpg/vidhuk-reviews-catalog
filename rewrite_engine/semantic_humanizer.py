def split_into_sentences(text: str) -> List[str]:
    """Splits text into sentences safely while keeping abbreviations intact."""
    protected = text
    abbrs = ["т.д.", "т.п.", "т.е.", "ул.", "г.", "м.", "грн.", "руб.", "стр.", "ім."]
    for i, a in enumerate(abbrs):
        protected = protected.replace(a, f"__ABBR{i}__")

    parts = re.split(r'([.!?]+(?:\s+|\n+|$))', protected)
    sentences = []
    current = ""
    for p in parts:
        current += p
        if re.search(r'[.!?]+(?:\s+|\n+|$)', p):
            sentences.append(current.strip())
            current = ""
    if current.strip():
        sentences.append(current.strip())

    restored = []
    for s in sentences:
        for i, a in enumerate(abbrs):
            s = s.replace(f"__ABBR{i}__", a)
        if s.strip():
            restored.append(s.strip())
    return restored if restored else [text]


def paraphrase_sentence(
    sentence: str,
    lang: str,
    seed: int,
    idx: int,
    total_sentences: int,
    rating: float
) -> str:
    """
    Paraphrases a single sentence:
    - Replaces multi-word phrases with idiomatic equivalents
    - Performs context-aware synonym substitutions
    - Adjusts sentence syntax and rhythm naturally
    """
    rng = random.Random(seed + idx * 7919)
    s = sentence.strip()

    # 1. Multi-word phrase rewrite
    phrase_mappings = UA_PHRASE_REWRITES if lang == "uk" else RU_PHRASE_REWRITES
    for pat, replacements in phrase_mappings:
        if pat.search(s):
            choice = rng.choice(replacements)
            s = pat.sub(choice, s, count=1)

    # 2. Word-level synonym substitutions
    syn_dict = UA_WORD_SYNONYMS if lang == "uk" else RU_WORD_SYNONYMS
    tokens = re.split(r'(\b[\w\x27\u2019-]+\b)', s)
    new_tokens = []
    for token in tokens:
        lower = token.lower()
        if lower in syn_dict and rng.random() < 0.65:
            options = syn_dict[lower]
            chosen = rng.choice(options)
            if token.istitle():
                chosen = chosen.capitalize()
            elif token.isupper():
                chosen = chosen.upper()
            new_tokens.append(chosen)
        else:
            new_tokens.append(token)
    s = "".join(new_tokens)

    return s.strip()


def humanize_review_text(
    original_text: str,
    lang: str,
    seed: int,
    rating: float,
    role: str = "klientov"
) -> str:
    """
    Completely humanizes and paraphrases raw review text:
    1. Unwraps awkward brackets into conversational flow
    2. Purges all em-dashes and en-dashes
    3. Replaces grammatical cliches
    4. Neutralizes sentiment polarity conflicts
    5. Strips remaining donor clichés
    6. Splits into sentences and paraphrases each sentence with semantic fidelity
    7. Reassembles text and sanitizes with deterministic rules
    """
    if not original_text or not original_text.strip():
        return ""

    raw = original_text.strip()

    # Step 1: Unwrap brackets
    unwrapped = unwrap_human_brackets(raw)

    # Step 2: Purge unicode dashes immediately
    dash_free = purge_unicode_dashes(unwrapped)

    # Step 3: Replace grammatical cliches
    grammatical = replace_grammatical_cliches(dash_free, lang=lang)

    # Step 4: Neutralize polarity conflicts
    neutralized = neutralize_polarity_conflicts(grammatical, rating=rating, lang=lang)

    # Step 5: Clean remaining donor clichés
    cleaned = neutralized
    for pat in COMPILED_ALL_CLICHES:
        cleaned = pat.sub("", cleaned)
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()

    # Step 6: Sentence-by-sentence paraphrase
    sentences = split_into_sentences(cleaned)
    rewritten_sentences = []
    for idx, sent in enumerate(sentences):
        rewritten_sentences.append(
            paraphrase_sentence(
                sent,
                lang=lang,
                seed=seed,
                idx=idx,
                total_sentences=len(sentences),
                rating=rating
            )
        )

    result_text = " ".join(rewritten_sentences)

    # Collapse any accidental double duplicate words
    result_text = re.sub(r'\b(\w{3,})\s+\1\b', r'\1', result_text, flags=re.I)

    # Step 7: Final deterministic sanitization
    sanitized = sanitize_review_text(result_text)
    sanitized = re.sub(r'\s+([,.:;!?])', r'\1', sanitized)
    sanitized = re.sub(r'([,.:;!?])\1+', r'\1', sanitized)
    sanitized = re.sub(r'[ \t]+', ' ', sanitized).strip()

    return sanitized


