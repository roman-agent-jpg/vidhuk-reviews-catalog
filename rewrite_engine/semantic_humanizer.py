def rewrite_single_review(record: Dict[str, Any]) -> Dict[str, Any]:
    """
    Takes raw record dict:
    - id
    - title
    - text
    - rating
    - review_type
    Returns dict:
    - rewritten_title
    - rewritten_text
    - rewritten_pros
    - rewritten_cons
    - rewrite_lang
    - rewrite_status ('done' or 'failed')
    - rewrite_error (None or error message)
    """
    rec_id = record.get("id") or 0
    orig_text = (record.get("text") or "").strip()
    orig_title = (record.get("title") or "").strip()
    role = record.get("review_type", "klientov")
    try:
        rating = float(record.get("rating") or 3.0)
    except (ValueError, TypeError):
        rating = 3.0

    lang = detect_language(orig_text, orig_title)

    # Humanize text
    new_text = humanize_review_text(
        orig_text,
        lang=lang,
        seed=rec_id,
        rating=rating,
        role=role
    )

    # Humanize title
    new_title = humanize_review_title(
        orig_title,
        body_text=new_text,
        lang=lang,
        seed=rec_id,
        rating=rating,
        role=role
    )

    # Synthesize pros & cons
    pros, cons = synthesize_pros_cons(
        new_text,
        lang=lang,
        rating=rating,
        seed=rec_id,
        role=role
    )

    # Safety: run full linter verification
    candidate = {
        "title": new_title,
        "text": new_text,
        "pros": pros,
        "cons": cons,
        "lang": lang
    }
    is_valid, errors = validate_rewritten_review(candidate, record)

    # If any error (e.g. residual cliché or polarity mismatch), purge it and re-verify
    if not is_valid:
        new_text = neutralize_polarity_conflicts(new_text, rating=rating, lang=lang)
        new_title = neutralize_polarity_conflicts(new_title, rating=rating, lang=lang)
        for pat in COMPILED_ALL_CLICHES:
            new_text = pat.sub("", new_text)
            new_title = pat.sub("", new_title)
            pros = pat.sub("", pros)
            cons = pat.sub("", cons)
        new_text = sanitize_review_text(new_text)
        new_title = sanitize_title(new_title)
        candidate = {
            "title": new_title,
            "text": new_text,
            "pros": pros,
            "cons": cons,
            "lang": lang
        }
        is_valid, errors = validate_rewritten_review(candidate, record)

    return {
        "id": rec_id,
        "rewritten_title": new_title[:180],
        "rewritten_text": new_text,
        "rewritten_pros": pros,
        "rewritten_cons": cons,
        "rewrite_lang": lang,
        "rewrite_status": "done" if is_valid else "failed",
        "rewrite_error": "; ".join(errors) if not is_valid else None,
        "rewrite_model": "semantic-humanizer-v2"
    }
