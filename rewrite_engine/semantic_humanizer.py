def detect_language(text: str, title: str = "") -> str:
    """Detects whether text is Ukrainian ('uk') or Russian ('ru')."""
    sample = f"{title} {text}".lower()
    uk_markers = len(re.findall(r'[іїєґ]', sample))
    ru_markers = len(re.findall(r'[ыэъё]', sample))
    if uk_markers > ru_markers:
        return "uk"
    if ru_markers > uk_markers:
        return "ru"
    uk_words = len(re.findall(r'\b(та|що|як|це|для|але|дуже|працю|відгук|був|була|мене|все)\b', sample))
    ru_words = len(re.findall(r'\b(и|что|как|это|для|но|очень|работ|отзыв|был|была|меня|всё)\b', sample))
    return "uk" if uk_words > ru_words else "ru"


def unwrap_human_brackets(text: str) -> str:
    """
    Unwraps non-standard, robotic, or conversational brackets into flowing natural clauses.
    Preserves purely technical/numeric specs like (128 ГБ) or (2023 г.) without AI brackets.
    """
    if not text or '(' not in text:
        return text

    def _replace_bracket(m: re.Match) -> str:
        content = m.group(1).strip()
        if re.match(r'^(?:[№#]?\s*\d+[\w\s$€₴.,%-]*|[A-Z0-9\s._-]{1,15})$', content, re.I):
            return f" ({content})"
        content = content.rstrip('.,;!?')
        return f", {content}, "

    cleaned = re.sub(r'\(([^()]{1,200})\)', _replace_bracket, text)
    cleaned = cleaned.replace('[', '').replace(']', '').replace('{', '').replace('}', '')
    return cleaned


def purge_unicode_dashes(text: str) -> str:
    """
    Guarantees strict zero em-dashes and en-dashes by rewriting them as
    commas, hyphens (intra-word only), or colons.
    """
    if not text:
        return ""
    t = re.sub(rf'(\d+)\s*{UNICODE_DASHES}\s*(\d+)', r'\1-\2', text)
    t = re.sub(rf'(^|\n)\s*{UNICODE_DASHES}\s*', r'\1- ', t)
    t = re.sub(rf',\s*{UNICODE_DASHES}\s*', ', ', t)
    t = re.sub(rf'{UNICODE_DASHES}\s*,', ', ', t)
    t = re.sub(rf'\s+{UNICODE_DASHES}\s+', ', ', t)
    t = re.sub(UNICODE_DASHES, '-', t)
    t = re.sub(r'-{2,}', '-', t)
    t = re.sub(r',\s*,+', ', ', t)
    t = re.sub(r',\s*-\s*', ', ', t)
    return t


